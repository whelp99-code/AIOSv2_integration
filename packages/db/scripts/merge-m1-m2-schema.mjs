#!/usr/bin/env node
/**
 * M1–M2 schema merge (C-1a):
 * M1 — BLRO starter 19 models as business SSOT
 * M2 — portal automation/kernel tables (Automation* prefix on conflicts)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DB_ROOT = join(__dirname, '..');
const BLRO = readFileSync(
  join(
    process.env.HOME,
    'Downloads/01.Pilot_Coding/blro_company_ops_agentic_os_bundle/starter/prisma/schema.prisma'
  ),
  'utf8'
);

const AUTH_AND_INTEGRATION = `
enum UserRole {
  USER
  ADMIN
}

model Account {
  id                String  @id @default(cuid())
  userId            String
  type              String
  provider          String
  providerAccountId String
  refresh_token     String?
  access_token      String?
  expires_at        Int?
  token_type        String?
  scope             String?
  id_token          String?
  session_state     String?

  user User @relation(fields: [userId], references: [id], onDelete: Cascade)

  @@unique([provider, providerAccountId])
  @@map("accounts")
}

model Session {
  id           String   @id @default(cuid())
  sessionToken String   @unique
  userId       String
  expires      DateTime

  user User @relation(fields: [userId], references: [id], onDelete: Cascade)

  @@map("sessions")
}

model VerificationToken {
  identifier String
  token      String   @unique
  expires    DateTime

  @@unique([identifier, token])
  @@map("verification_tokens")
}

model IntegrationHealth {
  id            String    @id @default(cuid())
  serviceKey    String    @unique @map("service_key")
  status        String    @default("unknown")
  lastCheckedAt DateTime? @map("last_checked_at")
  details       Json?
  createdAt     DateTime  @default(now()) @map("created_at")
  updatedAt     DateTime  @updatedAt @map("updated_at")

  @@map("integration_health")
}
`;

const PORTAL_AUTOMATION = readFileSync(
  join(DB_ROOT, 'prisma/portal-automation-additive.prisma'),
  'utf8'
);

/** Prisma 6 requires one enum value per line */
function normalizeEnums(schema) {
  return schema.replace(/enum (\w+) \{([^}]+)\}/g, (_match, name, values) => {
    const vals = values.trim().split(/\s+/).filter(Boolean);
    return `enum ${name} {\n${vals.map((v) => `  ${v}`).join('\n')}\n}`;
  });
}

let schema = normalizeEnums(BLRO);

// M1 patches — auth on User
schema = schema.replace(
  /model User \{[\s\S]*?\n\}/,
  `model User {
  id        String   @id @default(cuid())
  email     String   @unique
  name      String?
  imageUrl  String?
  role      UserRole @default(USER)
  createdAt DateTime @default(now())
  updatedAt DateTime @updatedAt
  memberships OrganizationMember[]
  runsStarted ExecutionRun[] @relation("RunStartedBy")
  approvalsRequested ApprovalItem[] @relation("ApprovalRequestedBy")
  accounts Account[]
  sessions Session[]
  automationProjectMembers AutomationProjectMember[]
  commandRuns CommandRun[] @relation("CommandRunRequestedBy")
}`
);

// Organization — missing inverse relations (BLRO starter gap) + M2 automation
schema = schema.replace(
  /ingestionJobs IngestionJob\[\]\n\}/,
  `ingestionJobs IngestionJob[]
  mailItems         MailItem[]
  proposals         Proposal[]
  presalesReviews   PresalesReview[]
  automationProjects AutomationProject[]
}`
);

// IngestionItem ↔ MailItem / ExecutionRun
schema = schema.replace(
  /(runs         ExecutionRun\[\]\n)(})/,
  `$1  ingestionItems IngestionItem[]
$2`
);

schema = schema.replace(
  /(approvals    ApprovalItem\[\]\n)(}\n\nmodel RunStep)/,
  `$1  ingestionItems IngestionItem[]
$2`
);

const header = `// C-Stack merged schema — M1 (BLRO SSOT) + M2 (portal automation additive)
// Generated by scripts/merge-m1-m2-schema.mjs — do not edit by hand; re-run merge script

`;

const out = header + schema + '\n' + AUTH_AND_INTEGRATION + '\n' + PORTAL_AUTOMATION + '\n';
const target = join(DB_ROOT, 'prisma/schema.prisma');
writeFileSync(target, out);
console.log('Wrote', target, `(${out.split('\n').length} lines)`);
